// ============================================================
// AI PROVIDERS
// ============================================================

const PROVIDERS = {
  ollama: ollamaProvider,
  groq: groqProvider,
  gemini: geminiProvider,
  mock: mockProvider,
};

// ============================================================
// GET ACTIVE PROVIDER
// ============================================================

function getProvider(explicitProviderName) {
  if (explicitProviderName && PROVIDERS[explicitProviderName]) {
    return PROVIDERS[explicitProviderName];
  }

  // If mock provider is explicitly configured via ENABLE_MOCK_PROVIDER or AI_PROVIDER_3 === "mock"
  if (ENABLE_MOCK_PROVIDER) {
    return PROVIDERS.mock;
  }

  const provider = PROVIDERS[AI_PROVIDER] || PROVIDERS.groq;

  if (!provider) {
    throw new Error(
      `Unknown AI_PROVIDER "${AI_PROVIDER}". Use ollama | groq | gemini | mock.`
    );
  }

  return provider;
}

// ============================================================
// JSON HELPERS
// ============================================================

function stripJsonFences(text) {
  if (typeof text !== "string") {
    return "";
  }

  return text
    .replace(/```json/gi, "")
    .replace(/```/g, "")
    .trim();
}

function safeParseJSON(text, fallback) {
  try {
    return JSON.parse(stripJsonFences(text));
  } catch {
    return fallback;
  }
}

// ============================================================
// NORMALIZATION HELPERS
// ============================================================

function score(value, fallback = 0) {
  const numeric = Number(value);

  return Number.isFinite(numeric)
    ? Math.max(0, Math.min(100, Math.round(numeric)))
    : fallback;
}

function stringList(value) {
  return Array.isArray(value)
    ? value
        .filter((item) => typeof item === "string")
        .map((item) => item.trim())
        .filter(Boolean)
    : [];
}

// ============================================================
// EVALUATION NORMALIZER
// ============================================================

function normalizeEvaluation(value) {
  return {
    correctness: score(value?.correctness, 50),
    clarity: score(value?.clarity, 50),
    confidence: score(value?.confidence, 50),

    notes:
      typeof value?.notes === "string"
        ? value.notes.trim()
        : "",
  };
}

// ============================================================
// FINAL REPORT NORMALIZER
// ============================================================

function normalizeReport(value) {
  return {
    overall: score(value?.overall, 50),
    technical: score(value?.technical, 50),
    communication: score(value?.communication, 50),
    confidence: score(value?.confidence, 50),
    problemSolving: score(value?.problemSolving, 50),
    coding: score(value?.coding, 0),

    strengths: stringList(value?.strengths),
    weaknesses: stringList(value?.weaknesses),
    suggestions: stringList(value?.suggestions),

    quotedMoments: Array.isArray(value?.quotedMoments)
      ? value.quotedMoments.filter(
          (item) =>
            item &&
            typeof item.quote === "string"
        )
      : [],

    summary:
      typeof value?.summary === "string"
        ? value.summary.trim()
        : "",
  };
}

